// Converts design/icons/svg/*.svg (Lucide) into Compose vector drawables + the LucideIcon enum.
// Run from the repo root after adding an icon:  node tools/lucide-to-vector.mjs
import { readFileSync, writeFileSync, readdirSync, mkdirSync } from "node:fs";

const SRC = "design/icons/svg";
const DS = "designsystem/src/commonMain";
const DRAWABLE = `${DS}/composeResources/drawable`;
const ENUM = `${DS}/kotlin/app/cragpack/designsystem/icon/LucideIcon.kt`;
const FILLED = new Set(["star"]); // icons that also get a filled variant ("the star fills when on")

const attrs = (el) => Object.fromEntries([...el.matchAll(/([\w-]+)="([^"]*)"/g)].map((m) => [m[1], m[2]]));
const n = (v) => Number(v ?? 0);

function toPath(tag, a) {
  switch (tag) {
    case "path": return a.d;
    case "line": return `M${a.x1} ${a.y1}L${a.x2} ${a.y2}`;
    case "polyline":
    case "polygon": {
      const p = a.points.trim().split(/[\s,]+/);
      let d = `M${p[0]} ${p[1]}`;
      for (let i = 2; i < p.length; i += 2) d += `L${p[i]} ${p[i + 1]}`;
      return tag === "polygon" ? d + "Z" : d;
    }
    case "circle": {
      const [cx, cy, r] = [n(a.cx), n(a.cy), n(a.r)];
      return `M${cx - r} ${cy}a${r} ${r} 0 1 0 ${2 * r} 0a${r} ${r} 0 1 0 ${-2 * r} 0Z`;
    }
    case "rect": {
      const [x, y, w, h] = [n(a.x), n(a.y), n(a.width), n(a.height)];
      const rx = Math.min(n(a.rx ?? a.ry), w / 2), ry = Math.min(n(a.ry ?? a.rx), h / 2);
      if (!rx) return `M${x} ${y}h${w}v${h}h${-w}Z`;
      return `M${x + rx} ${y}h${w - 2 * rx}a${rx} ${ry} 0 0 1 ${rx} ${ry}v${h - 2 * ry}` +
        `a${rx} ${ry} 0 0 1 ${-rx} ${ry}h${-(w - 2 * rx)}a${rx} ${ry} 0 0 1 ${-rx} ${-ry}` +
        `v${-(h - 2 * ry)}a${rx} ${ry} 0 0 1 ${rx} ${-ry}Z`;
    }
    default: throw new Error(`Unsupported SVG element <${tag}>`);
  }
}

function vector(paths, filled) {
  const fill = filled ? "#FF000000" : "#00000000";
  const body = paths.map((d) =>
    `  <path android:pathData="${d}" android:fillColor="${fill}" android:strokeColor="#FF000000"\n` +
    `      android:strokeWidth="2" android:strokeLineCap="round" android:strokeLineJoin="round"/>`).join("\n");
  return `<?xml version="1.0" encoding="utf-8"?>\n<!-- Generated from Lucide (ISC) by tools/lucide-to-vector.mjs. Do not edit. -->\n` +
    `<vector xmlns:android="http://schemas.android.com/apk/res/android"\n` +
    `    android:width="24dp" android:height="24dp" android:viewportWidth="24" android:viewportHeight="24">\n${body}\n</vector>\n`;
}

const pascal = (s) => s.split(/[-_]/).map((p) => p[0].toUpperCase() + p.slice(1)).join("");
mkdirSync(DRAWABLE, { recursive: true });
const entries = [];

for (const file of readdirSync(SRC).filter((f) => f.endsWith(".svg")).sort()) {
  const name = file.replace(/\.svg$/, "");
  const svg = readFileSync(`${SRC}/${file}`, "utf8");
  const paths = [...svg.matchAll(/<(path|circle|rect|line|polyline|polygon|ellipse)\b([^>]*)\/?>/g)]
    .map((m) => toPath(m[1], attrs(m[2])));
  const res = `ic_${name.replaceAll("-", "_")}`;
  writeFileSync(`${DRAWABLE}/${res}.xml`, vector(paths, false));
  entries.push([pascal(name), res]);
  if (FILLED.has(name)) {
    writeFileSync(`${DRAWABLE}/${res}_filled.xml`, vector(paths, true));
    entries.push([pascal(name) + "Filled", `${res}_filled`]);
  }
}

mkdirSync(ENUM.slice(0, ENUM.lastIndexOf("/")), { recursive: true });
writeFileSync(ENUM, `// Generated by tools/lucide-to-vector.mjs from design/icons/svg. Do not edit.
package app.cragpack.designsystem.icon

import app.cragpack.designsystem.generated.resources.*
import org.jetbrains.compose.resources.DrawableResource

/** Every icon the app may use (Lucide only, design rule 13). */
enum class LucideIcon(internal val res: DrawableResource) {
${entries.map(([k, r]) => `    ${k}(Res.drawable.${r}),`).join("\n")}
}
`);
console.log(`Wrote ${entries.length} icons`);
